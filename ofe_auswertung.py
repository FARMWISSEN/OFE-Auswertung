    def run_Rscript(self, rscript, parameter):
    
        # 1. Den R-Provider in QGIS suchen, um zu sehen, ob R überhaupt aktiv ist
        registry = QgsApplication.processingRegistry()
        r_provider = registry.providerById("r")
        if not r_provider:
            self.iface.messageBar().pushMessage("Fehler", "Der R Processing Provider ist in QGIS nicht aktiv oder nicht installiert!", level=2)
            #print("Der R Processing Provider ist in QGIS nicht aktiv oder nicht installiert!")
            return        
        
        # 2. Den konfigurierten R-Skriptordner direkt aus den QGIS-Settings auslesen
        settings = QgsSettings()
        # QGIS speichert den Pfad unter diesem spezifischen Schlüssel:
        qgis_r_ordner = settings.value("/Processing/R/rScriptsFolder", "")
        
        # Falls der Pfad in den Einstellungen leer ist, greift der QGIS-Standardpfad im Profil
        if not qgis_r_ordner:
            from qgis.core import QgsUserProfileManager
            profil_pfad = QgsApplication.qgisSettingsDirPath()
            qgis_r_ordner = os.path.join(profil_pfad, "processing", "rscripts")
        
        # 3. Pfade auflösen und validieren
        plugin_dir = os.path.dirname(os.path.abspath(__file__))
        quell_skript = os.path.join(plugin_dir, rscript + ".rsx")
        ziel_skript = os.path.join(qgis_r_ordner, rscript + ".rsx")
        
        # 4. Datei in den echten QGIS-R-Ordner kopieren
        try:
            if not os.path.exists(qgis_r_ordner):
                os.makedirs(qgis_r_ordner)
            shutil.copy2(quell_skript, ziel_skript)
            
            # Den Provider zwingen, seine Skripte aus dem Ordner neu zu laden
            r_provider.refreshAlgorithms()
        except Exception as e:
            self.iface.messageBar().pushMessage(
                "Fehler", f"Kopieren des R-Skripts fehlgeschlagen: {str(e)}", level=2
            )
            return       
    
    
        parameters = {
            'mein_vektorlayer': mFaktor2,
            'auswertungs_spalte': 'Sepal.Length',  # Name der Tabellenspalte
            'output_tabelle': 'TEMPORARY_OUTPUT'  # QGIS speichert das Ergebnis temporär
        }
        
        # 5. Algorithmus über seine offizielle QGIS-ID ausführen
        # Die ID setzt sich aus dem Provider-Kürzel "r" und dem Dateinamen (ohne .R) zusammen
        alg_id = "r:" + rscript
        
        try:
            feedback = QgsProcessingFeedback()
            ergebnis = processing.run(alg_id, parameters, feedback=feedback)
            
            # Ergebnis-Layer (Tabelle) anzeigen
            #from qgis.core import QgsProject
            #tabelle_pfad = ergebnis['output_tabelle']
            #QgsProject.instance().addMapLayer(QgsProject.instance().createMapLayer(tabelle_pfad, "R_Ergebnis"))
            
            self.iface.messageBar().pushMessage("Erfolg", "R-Skript via Plugin ausgeführt!", level=0)
        except Exception as e:
            self.iface.messageBar().pushMessage("Fehler", f"Fehler bei der Ausführung von {alg_id}: {str(e)}", level=2)
        
        return feedback
    
